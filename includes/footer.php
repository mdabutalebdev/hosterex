    // In-page Skeleton Transition Handler (Hosttio Style)
    window.handleSkeletonTransition = function() {
        if (window.skeletonTransitionStarted) return;
        
        const skeletons = document.querySelectorAll('.skeleton-container');
        const realContents = document.querySelectorAll('.real-content');
        
        if (window.waitForData && !window.dataFetched) return;

        window.skeletonTransitionStarted = true;
        console.log('Starting in-place transition...');

        // 1. Show real content first (it's underneath z-1)
        realContents.forEach(el => {
            el.classList.add('content-visible');
        });

        // 2. Fade out the skeleton (it's on top z-2)
        skeletons.forEach(el => {
            el.classList.add('skeleton-fade-out');
            // Remove from layout after fade
            setTimeout(() => el.style.display = 'none', 500);
        });

        document.body.classList.remove('loading-active');
    };

    // Execute logic
    const initiateTransition = () => {
        if (!window.waitForData) handleSkeletonTransition();
    };

    if (document.readyState === 'complete') {
        initiateTransition();
    } else {
        window.addEventListener('load', initiateTransition);
        document.addEventListener('DOMContentLoaded', initiateTransition);
    }

    // Emergency Fallback
    setTimeout(() => {
        window.dataFetched = true; 
        handleSkeletonTransition();
    }, 1500);
</script>

